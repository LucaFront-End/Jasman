// Parse real tire specifications strictly from the CSV product name
export function parseTireSpecs(product) {
  const rawName = product.name || '';
  const cleanTitle = rawName
    .replace(/^copia de\s+/i, '')
    .replace(/^Paquete de 2 Llantas\s+/i, 'Llanta ')
    .trim();

  let width = null;
  let profile = null;
  let rim = null;
  let measure = null;

  // 1. Standard metric: e.g. 195/65R15, 185/60 R15, 235/75/R15, 225/70R19.5
  const metricMatch = cleanTitle.match(/(\d{3})\s*\/\s*(\d{2})\s*\/?\s*R\s*(\d{2}(?:\.\d)?)/i);
  // 2. Flotation: e.g. 33X12.50R15, 27X8.50R14, 31X10.50R15
  const flotationMatch = cleanTitle.match(/(\d{2}X\d{1,2}\.\d{2})\s*R\s*(\d{2}(?:\.\d)?)/i);
  // 3. Commercial / LT without profile: e.g. 10R15
  const commercialMatch = cleanTitle.match(/\b(\d{2})R(\d{2}(?:\.\d)?)\b/i);

  if (metricMatch) {
    width = metricMatch[1];
    profile = metricMatch[2];
    rim = `R${metricMatch[3]}`;
    measure = `${width}/${profile}${rim}`;
  } else if (flotationMatch) {
    width = flotationMatch[1].toUpperCase();
    profile = 'Flotación';
    rim = `R${flotationMatch[2]}`;
    measure = `${width}${rim}`;
  } else if (commercialMatch) {
    width = commercialMatch[1];
    profile = 'LT';
    rim = `R${commercialMatch[2]}`;
    measure = `${width}${rim}`;
  }

  // Extract load & speed index (e.g. "91 H", "84T", "121/118 S", "128/126 N", "109 r")
  let loadSpeed = null;
  const loadSpeedEndMatch = cleanTitle.match(/\b(\d{2,3}(?:\/\d{2,3})?\s*[A-Z])\s*$/i);
  const loadSpeedInlineMatch = cleanTitle.match(/\b(\d{2,3}[THVWYQSRNM])\b/i);
  if (loadSpeedEndMatch) {
    loadSpeed = loadSpeedEndMatch[1].toUpperCase().replace(/\s+/, ' ');
  } else if (loadSpeedInlineMatch) {
    const raw = loadSpeedInlineMatch[1].toUpperCase();
    loadSpeed = `${raw.slice(0, -1)} ${raw.slice(-1)}`;
  }

  // Extract model line by stripping prefix, measure, brand, and load/speed index
  let model = cleanTitle
    .replace(/^(Paquete de 2 Llantas|Llanta)\s+/i, '')
    .replace(/(\d{3}\s*\/\s*\d{2}\s*\/?\s*R\s*\d{2}(?:\.\d)?|\d{2}X\d{1,2}\.\d{2}\s*R\s*\d{2}(?:\.\d)?|\b\d{2}R\d{2}(?:\.\d)?\b)/i, '')
    .replace(/\b(HK|CNT)\b/gi, '')
    .replace(new RegExp(product.brand, 'ig'), '')
    .replace(/Hankook|Continental|Euzkadi|General Tire|Laufenn/gi, '')
    .replace(/\b\d{2,3}(?:\/\d{2,3})?\s*[THVWYQSRNM]\b/gi, '')
    .replace(/\s+/g, ' ')
    .trim();

  const isPackage = false;
  const normalizedCategory =
    product.category === 'Paquetes' ? 'Llanta de automóvil' : product.category;
  const inStock = product.quantity > 0 && product.finalPriceTaxExcluded > 0;
  const hasPngCutout = true;
  const cutoutImage = `/images/tires/tire-${product.id}.png`;

  // Classify each tire into Auto, Camioneta (SUV/Pickup), or Camión (Carga/Van)
  let vehicleType = 'Auto';
  if (
    normalizedCategory === 'Llanta de camión' ||
    /19\.5|17\.5|10R15|VanContact|Vantra|RA08|RA18|AH11|DH35|Smart Work|SMaRT FLeX|6PR|8PR/i.test(
      cleanTitle
    )
  ) {
    vehicleType = 'Camión';
  } else if (
    /SUV|AT2|MT2|HTS60|Grabber|Dynapro|Overlander|All Terrain|285\/45R21|245\/75R17|235\/75|265\/70|31X10|33X12|27X8|205\/75R14/i.test(
      cleanTitle
    )
  ) {
    vehicleType = 'Camioneta';
  }

  const brandExcerpts = {
    Hankook:
      'Compuesto de sílice de alta dispersión desarrollado por Hankook como proveedor técnico oficial de la ABB FIA Formula E World Championship, optimizado para frenado preciso en piso seco y mojado, baja resistencia al rodamiento y máximo confort acústico.',
    Continental:
      'Ingeniería alemana con compuesto SafetySilica y diseño macro-bloque que maximiza el área de contacto en curvas, reduce la distancia de frenado y prolonga el kilometraje útil en ciudad y autopista.',
    Euzkadi:
      'Estructura reforzada de alta resistencia diseñada para las condiciones de los caminos en México, con hombros robustos que protegen contra impactos y brindan tracción confiable en todo terreno.',
    'General Tire':
      'Tecnología estadounidense con carcasa Duragen™ de ultra alta resistencia, ideal para SUVs y Pick-Ups que exigen estabilidad en carretera, capacidad de carga superior y desempeño todo terreno.',
    Laufenn:
      'Línea de alto desempeño respaldada por la ingeniería de Hankook Tire, con dibujo asimétrico de 4 canales longitudinales para evacuación rápida de agua y respuesta deportiva.',
  };

  const excerpt = `${cleanTitle} (${measure || 'Medida Oficial'}${
    loadSpeed ? ` · Índice ${loadSpeed}` : ''
  }) para ${vehicleType.toLowerCase()}. ${
    brandExcerpts[product.brand] || brandExcerpts.Hankook
  }`;

  return {
    ...product,
    category: normalizedCategory,
    cleanTitle,
    width,
    profile,
    rim,
    measure,
    loadSpeed,
    model: model || cleanTitle,
    excerpt,
    isPackage,
    unitsPerItem: 1,
    inStock,
    hasPngCutout,
    cutoutImage,
    vehicleType,
    primaryImage: product.images[0] || '/images/service-tires.png',
  };
}

